import base64
from pathlib import Path
from PIL import Image, ImageDraw, ImageFilter

ROOT = Path(__file__).resolve().parent
SIZE = 1024
SCALE = SIZE / 512


def s(value):
    return int(round(value * SCALE))


def box(values):
    return tuple(s(v) for v in values)


def rounded_line(draw, points, fill, width):
    scaled = [(s(x), s(y)) for x, y in points]
    pixel_width = s(width)
    radius = pixel_width / 2
    draw.line(scaled, fill=fill, width=pixel_width, joint="curve")
    for x, y in (scaled[0], scaled[-1]):
        draw.ellipse((x - radius, y - radius, x + radius, y + radius), fill=fill)


image = Image.new("RGBA", (SIZE, SIZE), (0, 0, 0, 0))

# Soft tile shadow.
shadow = Image.new("RGBA", image.size, (0, 0, 0, 0))
shadow_draw = ImageDraw.Draw(shadow)
shadow_draw.rounded_rectangle(box((34, 42, 486, 494)), radius=s(82), fill=(5, 24, 39, 115))
shadow = shadow.filter(ImageFilter.GaussianBlur(s(14)))
image.alpha_composite(shadow)

# Rounded blue tile with a subtle vertical gradient.
tile_mask = Image.new("L", image.size, 0)
ImageDraw.Draw(tile_mask).rounded_rectangle(box((24, 24, 488, 488)), radius=s(82), fill=255)
gradient = Image.new("RGBA", image.size)
gradient_pixels = gradient.load()
for y in range(SIZE):
    t = max(0.0, min(1.0, (y - s(24)) / s(464)))
    start = (31, 93, 139)
    end = (18, 55, 86)
    color = tuple(int(start[i] * (1 - t) + end[i] * t) for i in range(3)) + (255,)
    for x in range(SIZE):
        gradient_pixels[x, y] = color
image.alpha_composite(Image.composite(gradient, Image.new("RGBA", image.size), tile_mask))

draw = ImageDraw.Draw(image)

