import base64
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent
SOURCE = ROOT / "pobuca-icon-512.png"

# The source PNG is a transparent rasterization of pobuca-icon.svg, which
# contains the original icon extracted from the official Pobuca wordmark.
with Image.open(SOURCE) as source:
    image = source.convert("RGBA")
    for size in (512, 80, 32):
        resized = image if image.size == (size, size) else image.resize(
            (size, size), Image.Resampling.LANCZOS
        )
        resized.save(ROOT / f"audit-manager-logo-{size}.png", optimize=True)

small_base64 = base64.b64encode(
    (ROOT / "audit-manager-logo-32.png").read_bytes()
).decode("ascii")
big_base64 = base64.b64encode(
    (ROOT / "audit-manager-logo-80.png").read_bytes()
).decode("ascii")
resources = f'''// Generated by assets/generate_logo.py. Do not edit manually.
namespace DataverseAuditManager.XrmToolBox
{{
    internal static class LogoResources
    {{
        public const string Small = "{small_base64}";
        public const string Big = "{big_base64}";
    }}
}}
'''
(ROOT.parent / "LogoResources.cs").write_text(resources, encoding="utf-8")

print("Generated:")
for path in sorted(ROOT.glob("audit-manager-logo-*.png")):
    print(path)
print(ROOT.parent / "LogoResources.cs")
